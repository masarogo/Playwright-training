//Relational or Comparison Operators

// > more than
// < less than
// >= more than equal
// <= less than equal

var result = 10 > 5
console.log(result)

// Equality Operators
var x = 1
console.log(x == '1') // lose comparison: con doble = se compara el valor de la izquierda con el de la derecha
console.log(x === '1') // strict comparison: no estamos chequeando solo el valor sino el datatype. como la variable x esta sin quotes, este ultimo lo toma como string